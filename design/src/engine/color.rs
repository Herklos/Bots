use super::*;

// ---------- contrast (WCAG 2.x) ----------

pub(crate) fn channel(hex: &str, at: usize) -> f64 {
    let c = f64::from(u8::from_str_radix(&hex[at..at + 2], 16).unwrap_or(0)) / 255.0;
    if c <= 0.04045 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    }
}

/// Relative luminance of `#rrggbb`.
pub fn luminance(hex: &str) -> f64 {
    let h = hex.trim_start_matches('#');
    0.2126 * channel(h, 0) + 0.7152 * channel(h, 2) + 0.0722 * channel(h, 4)
}

/// Contrast ratio of two `#rrggbb` colours, from 1 to 21.
pub fn contrast(a: &str, b: &str) -> f64 {
    let (x, y) = (luminance(a), luminance(b));
    (x.max(y) + 0.05) / (x.min(y) + 0.05)
}

/// The ink for text on a fill: Night or white, whichever reads better.
pub fn ink_on(fill: &str) -> &'static str {
    let t = tokens();
    if contrast(&t.color.night, fill) >= contrast(&t.color.white, fill) {
        &t.color.night
    } else {
        &t.color.white
    }
}

pub(crate) fn num(n: f64) -> String {
    let s = format!("{n:.2}");
    s.trim_end_matches('0').trim_end_matches('.').to_string()
}

// ---------- generated text ----------

pub(crate) const NOTE: &str =
    "Generated by `cargo run -p hbots-design -- sync` from design/tokens.json.";

/// The token a palette name maps to in the app's design: Tide is `brand.default`, the other
/// avatar colours are `brand.<name>`. The app stores plain names; the design names the tokens.
pub fn brand_token(name: &str) -> String {
    if name == tokens().avatar.default {
        "brand.default".to_string()
    } else {
        format!("brand.{name}")
    }
}

/// The ink on an avatar colour, as a design token: white ink on a fill that reads better with it.
pub(crate) fn ink_token(hex: &str) -> &'static str {
    if ink_on(hex) == tokens().color.white {
        "ink.light"
    } else {
        "ink.dark"
    }
}

/// The app's design, `app/app.tamber`: the tint, the avatar colours as tokens, the inks, and
/// the base scale.
pub fn tamber() -> String {
    let t = tokens();
    let c = &t.color;
    let mut s = String::new();
    let _ = writeln!(s, "// {NOTE} Do not edit.");
    let _ = writeln!(s, "// The guidelines are in design/docs/.");
    let _ = writeln!(s, "tamber hbots\n\ntheme");
    let _ = writeln!(
        s,
        "  // The tint: Tide, darkened on light and lightened on dark so it reads as text."
    );
    let _ = writeln!(
        s,
        "  AccentColor = light-dark({}, {})",
        c.accent.light, c.accent.dark
    );
    let _ = writeln!(
        s,
        "  // The avatar colours. Each keeps its value in both schemes."
    );
    for (name, hex) in t.avatar.all() {
        let _ = writeln!(s, "  {} = {hex}  scheme=fixed", brand_token(name));
    }
    let _ = writeln!(
        s,
        "  // The ink on an avatar colour: white or Night, by its contrast."
    );
    let _ = writeln!(s, "  ink.light = {}  scheme=fixed", c.white);
    let _ = writeln!(s, "  ink.dark = {}  scheme=fixed", c.night);
    let _ = writeln!(
        s,
        "  // Semantic surfaces and secondary ink, shared by every screen."
    );
    for (name, pair) in &t.surface {
        let _ = writeln!(
            s,
            "  surface.{name} = light-dark({}, {})",
            pair.light, pair.dark
        );
    }
    let _ = writeln!(
        s,
        "  ink.muted = light-dark({}, {})",
        c.muted.light, c.muted.dark
    );
    let _ = writeln!(
        s,
        "  ink.faint = light-dark({}, {})",
        c.faint.light, c.faint.dark
    );
    let _ = writeln!(s, "  // Spacing and corners.");
    for k in ["xs", "sm", "md", "lg", "xl"] {
        let _ = writeln!(s, "  space.{k} = {}px", t.space[k]);
    }
    for k in ["sm", "md", "lg", "full"] {
        let _ = writeln!(s, "  radius.{k} = {}px", t.radius[k]);
    }
    s
}
