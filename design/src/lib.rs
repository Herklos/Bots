//! The hbots brand in one place.
//!
//! `tokens.json` is the source. This crate reads it, checks the brand's own rules (contrast,
//! the palette) and writes every file that repeats a brand value: the app's design
//! (`app/app.tamber`), the marked regions of `app/app.ts`, `app/app.contract` and
//! `app/face.contract`, `app/app.json`, a stylesheet and the logo files. `hbots-design sync`
//! writes them; `hbots-design check` and this crate's tests fail when one is out of step.
//!
//! The guidelines are in `design/docs/`.
use serde::Deserialize;
use std::{
    collections::BTreeMap,
    fmt::Write as _,
    path::{Path, PathBuf},
    sync::LazyLock,
};

pub const TOKENS_JSON: &str = include_str!("../tokens.json");

/// The mark, for a gateway that serves a page with no icon of its own.
pub const FAVICON_SVG: &str = include_str!("../assets/favicon.svg");

#[derive(Debug, Deserialize)]
pub struct Tokens {
    pub brand: Brand,
    pub color: Colors,
    pub avatar: Avatar,
    pub space: BTreeMap<String, u32>,
    pub radius: BTreeMap<String, u32>,
    pub size: BTreeMap<String, u32>,
    pub motion: Motion,
    pub face: Face,
}

#[derive(Debug, Deserialize)]
pub struct Brand {
    pub name: String,
    pub tagline: String,
    pub promise: String,
    pub traits: Vec<String>,
}

/// A colour with a value for each scheme.
#[derive(Debug, Deserialize, Clone)]
pub struct Pair {
    pub light: String,
    pub dark: String,
}

#[derive(Debug, Deserialize)]
pub struct Colors {
    /// The brand colour: the Face, the icon, a brand fill.
    pub tide: String,
    /// The dark neutral: ink on Tide, the dark canvas.
    pub night: String,
    /// The light neutral: the light canvas.
    pub paper: String,
    /// An outline that reads on both canvases.
    pub mist: String,
    pub white: String,
    /// Tide made readable as text and as a control: the app's tint.
    pub accent: Pair,
    pub muted: Pair,
    pub danger: Pair,
    pub success: Pair,
    pub warning: Pair,
    pub info: Pair,
}

#[derive(Debug, Deserialize)]
pub struct Avatar {
    /// The colour name a new Bot gets.
    pub default: String,
    /// The names the app offers, in order.
    pub picker: Vec<String>,
    /// Every name a `bot.json` may carry, in the order they are listed.
    pub colors: serde_json::Map<String, serde_json::Value>,
}

#[derive(Debug, Deserialize)]
pub struct Motion {
    pub fast_ms: u32,
    pub base_ms: u32,
    pub slow_ms: u32,
    pub face: BTreeMap<String, f64>,
}

#[derive(Debug, Deserialize)]
pub struct Face {
    pub radius: f64,
    pub eye: Eye,
}

#[derive(Debug, Deserialize)]
pub struct Eye {
    pub gap: f64,
    pub width: f64,
    pub length: f64,
    pub y: f64,
    pub corner: f64,
}

static TOKENS: LazyLock<Tokens> =
    LazyLock::new(|| serde_json::from_str(TOKENS_JSON).expect("design/tokens.json is valid"));

pub fn tokens() -> &'static Tokens {
    &TOKENS
}

impl Avatar {
    /// `(name, hex)` for every avatar colour, in the listed order.
    pub fn all(&self) -> Vec<(&str, &str)> {
        self.colors
            .iter()
            .filter_map(|(k, v)| Some((k.as_str(), v.as_str()?)))
            .collect()
    }

    pub fn hex(&self, name: &str) -> Option<&str> {
        self.colors.get(name).and_then(|v| v.as_str())
    }

    /// The hex of the colour a new Bot gets.
    pub fn default_hex(&self) -> &str {
        self.hex(&self.default)
            .expect("avatar.default names a colour")
    }
}

// ---------- contrast (WCAG 2.x) ----------

fn channel(hex: &str, at: usize) -> f64 {
    let c = u8::from_str_radix(&hex[at..at + 2], 16).unwrap_or(0) as f64 / 255.0;
    if c <= 0.04045 {
        c / 12.92
    } else {
        ((c + 0.055) / 1.055).powf(2.4)
    }
}

/// Relative luminance of `#rrggbb`.
pub fn luminance(hex: &str) -> f64 {
    let h = hex.trim_start_matches('#');
    0.2126 * channel(h, 0) + 0.7152 * channel(h, 2) + 0.0722 * channel(h, 4)
}

/// Contrast ratio of two `#rrggbb` colours, from 1 to 21.
pub fn contrast(a: &str, b: &str) -> f64 {
    let (x, y) = (luminance(a), luminance(b));
    (x.max(y) + 0.05) / (x.min(y) + 0.05)
}

/// The ink for text on a fill: Night or white, whichever reads better.
pub fn ink_on(fill: &str) -> &'static str {
    let t = tokens();
    if contrast(&t.color.night, fill) >= contrast(&t.color.white, fill) {
        &t.color.night
    } else {
        &t.color.white
    }
}

fn num(n: f64) -> String {
    let s = format!("{n:.2}");
    s.trim_end_matches('0').trim_end_matches('.').to_string()
}

