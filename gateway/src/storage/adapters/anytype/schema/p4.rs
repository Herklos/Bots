use super::table::{Column, Table};

const fn column(key: &'static str, format: &'static str) -> Column {
    Column {
        key,
        name: key,
        format,
        options: &[],
    }
}
const fn select(key: &'static str, options: &'static [&'static str]) -> Column {
    Column {
        key,
        name: key,
        format: "select",
        options,
    }
}
const fn table(
    key: &'static str,
    layout: &'static str,
    properties: &'static [&'static str],
) -> Table {
    Table {
        key,
        name: key,
        layout,
        properties,
    }
}

